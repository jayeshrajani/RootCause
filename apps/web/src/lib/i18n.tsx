const LANGUAGE_NAMES: Record<Language, string> = {
  en: "English",
  hi: "Hindi",
  pa: "Punjabi",
  es: "Spanish",
  fr: "French",
};

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey) => string;
  languageName: string;
}

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "rootcause.language";

function isLanguage(value: string | null): value is Language {
  return value !== null && LANGUAGES.includes(value as Language);
}

function getLanguageSnapshot(): Language {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return isLanguage(stored) ? stored : "en";
  } catch {
    return "en";
  }
}

function getServerLanguageSnapshot(): Language {
  return "en";
}

function subscribeToLanguageChanges(onChange: () => void): () => void {
  window.addEventListener("storage", onChange);
  window.addEventListener("rootcause-language-change", onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener("rootcause-language-change", onChange);
  };
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(
    subscribeToLanguageChanges,
    getLanguageSnapshot,
    getServerLanguageSnapshot,
  );

  useEffect(() => {
    document.documentElement.lang = language;
    const fontFamily = language === "hi"
      ? "var(--font-devanagari), sans-serif"
      : language === "pa"
        ? "var(--font-gurmukhi), sans-serif"
        : "var(--font-outfit), sans-serif";
    document.body.style.fontFamily = fontFamily;
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } finally {
      window.dispatchEvent(new Event("rootcause-language-change"));
    }
  }, []);

  const t = useCallback(
    (key: MessageKey) => TRANSLATIONS[language]?.[key] ?? EN[key],
    [language],
  );

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, languageName: LANGUAGE_NAMES[language] }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

